# версия плагина берётся из build.js (он же пишет manifest.json) - иначе документация расходится со сборкой.
# Сначала ищем объявленную константу VERSION, потом - литерал в манифесте (build.js старых версий).
_BUILD = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "build.js"), encoding="utf-8").read()
_m = _re.search(r'VERSION\s*=\s*"([0-9.]+)"', _BUILD) or _re.search(r'version: "([0-9.]+)"', _BUILD)
