import json
_S = json.load(open(os.path.join(ROOT, ".vault-stats.json"), encoding="utf-8"))
_missing = [k for k in ("degreeByType", "radiusByType", "edges", "maxDegree") if k not in _S]
if _missing:
    raise SystemExit(".vault-stats.json без полей %s — сначала запустите `node write_stats.js` "
                     "(он считает статистику тем же кодом, что плагин)." % ", ".join(_missing))
_DEG = _S["degreeByType"]
_RAD = _S["radiusByType"]


def _rng(d, key, fmt="{:.0f}"):
    v = d[key]
    return (fmt + "–" + fmt).format(v["min"], v["max"])


def _fmt_deg(key):
    v = _DEG[key]
    return "{} ({} разных значений)".format(_rng(_DEG, key), v["uniq"])


TOK = {
    "__CH__": str(_S["chapters"]), "__SE__": str(_S["sections"]),
    "__HE__": str(_S["headings"]), "__BL__": str(_S["blocks"]), "__NODES__": str(_S["nodes"]),
    "__EDGES__": str(_S["edges"]), "__MAXDEG__": str(_S["maxDegree"]),
    "__KWEDGES__": str(_S.get("keywordEdges", 0)),
    "__KWNODES__": str(_S.get("keywordNodes", 0)),
    "__MAXKWWEIGHT__": str(_S.get("maxKeywordWeight", 0)),
    "__KWSHARE__": str(_S.get("keywordBlocksShare", 0)),
    "__UNRES__": str(_S["unresolved"]), "__ORPH__": str(_S["orphans"]),
    "__COMP__": str(_S.get("components", 0)),
    # ссылки из оглавления (вершины-хаба) вычтены: «ссылок на неё» на доске = refs
    # во frontmatter = то, из чего плагин считает размер вершины
    "__REFS__": 'length(filter(file.inlinks, (l) => l.path != "Course Index.md"))',
    "__TOC__": str(_S.get("indexLinks", 0)),
    "__DEGCH__": _fmt_deg("chapter"), "__DEGSE__": _fmt_deg("section"),
    "__DEGHE__": _fmt_deg("heading"), "__DEGBL__": _fmt_deg("block"),
    "__RADMIN__": "{:.0f}".format(min(v["min"] for v in _RAD.values())),
    "__RADMAX__": "{:.0f}".format(max(v["max"] for v in _RAD.values())),
    "__RADCH__": _rng(_RAD, "chapter", "{:.0f}"), "__RADSE__": _rng(_RAD, "section", "{:.0f}"),
    "__RADHE__": _rng(_RAD, "heading", "{:.0f}"), "__RADBL__": _rng(_RAD, "block", "{:.0f}"),
}


def write(rel, text):
    full = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    for k, v in TOK.items():
        text = text.replace(k, v)
    with open(full, "w", encoding="utf-8") as fh:
        fh.write(text if text.endswith("\n") else text + "\n")
    print("  wrote", rel)


